
package com.example.scamshield;

import android.content.Context;
import android.content.Intent;

import java.text.SimpleDateFormat;
import java.util.Date;
import java.util.Locale;

public class ScanReportHelper {

    public static String generateReport(ScanRecord scan) {

        SimpleDateFormat formatter =
                new SimpleDateFormat(
                        "dd MMM yyyy, hh:mm a",
                        Locale.getDefault()
                );

        String scanDate = formatter.format(
                new Date(scan.getScannedAt())
        );

        return "SCAMSHIELD SECURITY REPORT\n"
                + "============================\n\n"

                + "Scan Type: " + scan.getScanType() + "\n"
                + "Risk Score: " + scan.getRiskScore() + "/100\n"
                + "Risk Level: " + scan.getRiskLevel() + "\n"
                + "Scan Date: " + scanDate + "\n\n"

                + "SCANNED CONTENT\n"
                + "----------------------------\n"
                + scan.getScannedContent() + "\n\n"

                + "SECURITY ANALYSIS\n"
                + "----------------------------\n"
                + (scan.getExplanation() == null
                ? "No explanation available."
                : scan.getExplanation())
                + "\n\n"

                + "Generated by ScamShield\n"
                + "Stay alert. Stay protected.";
    }

    public static void shareScan(
            Context context,
            ScanRecord scan
    ) {

        String report = generateReport(scan);

        Intent shareIntent = new Intent(Intent.ACTION_SEND);

        shareIntent.setType("text/plain");

        shareIntent.putExtra(
                Intent.EXTRA_SUBJECT,
                "ScamShield Security Report - "
                        + scan.getRiskLevel()
        );

        shareIntent.putExtra(
                Intent.EXTRA_TEXT,
                report
        );

        Intent chooser = Intent.createChooser(
                shareIntent,
                "Share Security Report"
        );

        context.startActivity(chooser);
    }
}
